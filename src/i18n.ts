export function getT(lang: Lang): (key: string, vars?: Record<string, string | number>) => string {
  return (key, vars) => {
    const entry = I18N[lang][key]
    const s: string = typeof entry === 'string' ? entry : (I18N.en[key] ?? key)
    if (vars) {
      let out = s
      for (const k in vars) out = out.split(`{${k}}`).join(String(vars[k]))
      return out
    }
    return s
  }
}

